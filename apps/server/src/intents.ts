import {
  BALANCE,
  buyMouli,
  buyRoom,
  type GameState,
  type HireKind,
  hire,
  type IntentError,
  type IntentResult,
  maxLevel,
  type StageId,
  setStrictness,
  train,
  upgradeMouli,
} from "@epidle/core";

// What a client can ask for. Validated by JSON schema first, then by the core rules.

/** Repeatable intents accept a count so "hire x10" is one request, not ten. */
export const MAX_COUNT = 100;

export type Intent = { requestId: string } & (
  | { type: "hire"; kind: HireKind; count?: number }
  | { type: "train"; devId: number; targetLevel?: number }
  | { type: "buyRoom"; count?: number }
  | { type: "buyMouli"; stage: StageId; count?: number }
  | { type: "upgradeMouli"; stage: StageId; count?: number }
  | { type: "setStrictness"; stage: StageId; level: number }
);

const count = { type: "integer", minimum: 1, maximum: MAX_COUNT };
const stage = { type: "string", enum: BALANCE.stages.map((s) => s.id) };

function branch(type: Intent["type"], properties: object, required: string[] = []) {
  return {
    type: "object",
    additionalProperties: false,
    required: ["type", "requestId", ...required],
    properties: {
      type: { const: type },
      // Generated by the client per action (a UUID fits), used to reject replays.
      requestId: { type: "string", pattern: "^[A-Za-z0-9_-]{8,64}$" },
      ...properties,
    },
  };
}

export const INTENT_SCHEMA = {
  oneOf: [
    branch("hire", { kind: { type: "string", enum: Object.keys(BALANCE.hire.kinds) }, count }, [
      "kind",
    ]),
    branch(
      "train",
      {
        devId: { type: "integer", minimum: 1, maximum: 1_000_000_000 },
        targetLevel: { type: "integer", minimum: 1, maximum: maxLevel() },
      },
      ["devId"],
    ),
    branch("buyRoom", { count }),
    branch("buyMouli", { stage, count }, ["stage"]),
    branch("upgradeMouli", { stage, count }, ["stage"]),
    branch(
      "setStrictness",
      { stage, level: { type: "integer", minimum: 0, maximum: BALANCE.strictness.length - 1 } },
      ["stage", "level"],
    ),
  ],
};

function step(state: GameState, intent: Intent): IntentResult {
  switch (intent.type) {
    case "hire":
      return hire(state, intent.kind);
    case "train":
      return train(state, intent.devId, intent.targetLevel);
    case "buyRoom":
      return buyRoom(state);
    case "buyMouli":
      return buyMouli(state, intent.stage);
    case "upgradeMouli":
      return upgradeMouli(state, intent.stage);
    case "setStrictness":
      return setStrictness(state, intent.stage, intent.level);
  }
}

export interface IntentOutcome {
  state: GameState;
  /** How many times the intent was applied (less than count if money ran out). */
  applied: number;
  /** Why it stopped before count, null if it did not. */
  error: IntentError | null;
}

/** Applies the intent up to `count` times, stopping at the first refusal. */
export function applyIntent(state: GameState, intent: Intent): IntentOutcome {
  const times = "count" in intent ? (intent.count ?? 1) : 1;
  let s = state;
  for (let applied = 0; applied < times; applied++) {
    const r = step(s, intent);
    if (!r.ok) return { state: s, applied, error: r.error };
    s = r.state;
  }
  return { state: s, applied: times, error: null };
}
